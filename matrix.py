#numpy нужен для работы с матрицами
import numpy as np

#просим пользователя ввести размеры матрицы
n = int(input("Введите количество строк N: "))
m = int(input("Введите количество столбцов M: "))

#создаём матрицу из случайных целых чисел от 0 до 9
a = np.random.randint(0, 10, (n, m))
print("Матрица:")
print(a)

#транспонируем матрицу (строки становятся столбцами)
t = a.T
print("Транспонированная матрица:")
print(t)

#определитель можно найти только у квадратной матрицы (когда N равно M)
if n == m:
    #вычисляем определитель исходной матрицы
    det_a = np.linalg.det(a)
    #вычисляем определитель транспонированной матрицы
    det_t = np.linalg.det(t)
    #выводим на экран 
    print("Определитель матрицы:", round(det_a, 2))
    print("Определитель транспонированной матрицы:", round(det_t, 2))

    #сравниваем определители (округляем, потому что числа дробные)
    if round(det_a, 2) == round(det_t, 2):
        print("Определители равны")
    else:
        print("Определители не равны")
else:
    print("Матрица не квадратная, определитель найти нельзя")
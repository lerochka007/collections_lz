#используем pandas, чтобы хранить данные в таблице (DataFrame)
import pandas as pd

#создаём пустую таблицу с нужными столбцами
book = pd.DataFrame(columns=["ФИО", "Адрес", "Телефон", "Дата рождения"])

#делаем бесконечный цикл, чтобы меню показывалось снова и снова
while True:
    #выводим меню, чтобы пользователь понимал, что можно делать
    print()
    print("Адресная книга")
    print("1 - Показать все записи")
    print("2 - Добавить запись")
    print("3 - Удалить запись")
    print("4 - Изменить запись")
    print("0 - Выход")

    #спрашиваем, что хочет сделать пользователь
    vybor = input("Введите номер действия: ")

    if vybor == "1":
        #показываем таблицу
        if len(book) == 0:
            print("Книга пока пустая")
        else:
            print(book)

    elif vybor == "2":
        #просим ввести данные нового человека
        fio = input("Введите ФИО: ")
        address = input("Введите адрес: ")
        phone = input("Введите телефон: ")
        birth = input("Введите дату рождения: ")
        #добавляем новую строку в конец таблицы
        book.loc[len(book)] = [fio, address, phone, birth]
        print("Запись добавлена!")

    elif vybor == "3":
        #сначала показываем таблицу, чтобы было видно номера строк
        print(book)
        number = int(input("Введите номер строки, которую удалить: "))
        #удаляем строку и пересчитываем номера заново (0, 1, 2...)
        book = book.drop(number)
        book = book.reset_index(drop=True)
        print("Запись удалена!")

    elif  vybor == "4":
        #показываем таблицу, чтобы было видно номера строк
        print(book)
        number = int(input("Введите номер строки, которую изменить: "))
        #спрашиваем, какой столбец менять
        column = input("Что изменить (ФИО, Адрес, Телефон, Дата рождения)? ")
        #записываем новое значение в нужную клетку таблицы
        book.loc[number, column] = input("Введите новое значение: ")
        print("Запись изменена!")

    elif vybor == "0":
        #выходим из цикла, программа заканчивается
        print("Пок")
        break

    else:
        #если ввели что-то непонятное
        print("Такого пункта нет, попробуйте ещё раз")